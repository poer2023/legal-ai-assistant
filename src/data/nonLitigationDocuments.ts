export interface DocumentTable {
  headers: string[];
  rows: string[][];
}

export interface DocumentSection {
  title: string;
  paragraphs?: string[];
  items?: string[];
  table?: DocumentTable;
}

export interface DocumentTemplateVariant {
  id: string;
  name: string;
  preview: string;
  requiredFields: string[];
  tags: string[];
  documentSections: DocumentSection[];
}

export interface NonLitigationDocument {
  id: string;
  name: string;
  skillName: string;
  category: string;
  phase: string;
  scenario: string;
  inputs: string;
  output: string;
  routeName: string;
  tags: string[];
  requiredFields: string[];
  focus: string[];
  workflow: string[];
  qualityChecks: string[];
  guardrails: string[];
  preview: string;
  updatedAt: string;
  documentSections: DocumentSection[];
  templateVariants: DocumentTemplateVariant[];
}

const updatedAt = '2026-05-08';

const row = (name: string, note = '根据项目材料填写，不确定时保留待确认'): string[] => [
  name,
  `【${name}】`,
  note,
];

const basicInfo = (fields: string[]): DocumentSection => ({
  title: '一、基础信息',
  table: {
    headers: ['项目', '填写内容', '填写说明'],
    rows: fields.map((field) => row(field)),
  },
});

const focusSection = (items: string[]): DocumentSection => ({
  title: '二、核心内容',
  items,
});

const workflowSection = (items: string[]): DocumentSection => ({
  title: '三、处理步骤',
  items,
});

const qualitySection = (items: string[]): DocumentSection => ({
  title: '四、复核要点',
  items,
});

const templateVariant = (
  id: string,
  name: string,
  preview: string,
  fields: string[],
  contentItems: string[],
  tags: string[],
  checks = ['字段完整且与场景匹配。', '不确定事项保留待确认，不直接写成确定结论。'],
): DocumentTemplateVariant => ({
  id,
  name,
  preview,
  requiredFields: fields,
  tags,
  documentSections: [
    basicInfo(fields),
    focusSection(contentItems),
    {
      title: '三、输出结构',
      items: [
        '先列明适用前提和材料范围。',
        '正文按业务流程或法律关系分层组织。',
        '结尾保留待确认事项、附件或后续动作清单。',
      ],
    },
    qualitySection(checks),
  ],
});

const createDocument = (
  input: Omit<NonLitigationDocument, 'updatedAt' | 'documentSections' | 'templateVariants'> & {
    documentSections?: DocumentSection[];
    templateVariants?: DocumentTemplateVariant[];
  },
): NonLitigationDocument => ({
  ...input,
  updatedAt,
  documentSections: input.documentSections ?? [
    basicInfo(input.requiredFields),
    focusSection(input.focus),
    workflowSection(input.workflow),
    qualitySection(input.qualityChecks),
    {
      title: '五、待补充事项',
      table: {
        headers: ['事项', '影响', '处理建议'],
        rows: [['【待补充事项】', '【影响范围】', '【追问或核验建议】']],
      },
    },
  ],
  templateVariants: input.templateVariants ?? [],
});

