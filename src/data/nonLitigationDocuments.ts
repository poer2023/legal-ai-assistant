export const isDefaultDocument = (id: string) =>
  (defaultDocumentIds as readonly string[]).includes(id);

export interface DocumentTemplateEntry {
  id: string;
  name: string;
  preview: string;
  requiredFields: string[];
  tags: string[];
  documentSections: DocumentSection[];
}

export const getDocumentTemplateEntries = (document: NonLitigationDocument): DocumentTemplateEntry[] => [
  {
    id: document.id,
    name: document.name,
    preview: document.preview,
    requiredFields: document.requiredFields,
    tags: document.tags,
    documentSections: document.documentSections,
  },
  ...document.templateVariants,
];

export const getDocumentTemplateIds = (document: NonLitigationDocument) =>
  getDocumentTemplateEntries(document).map((template) => template.id);

const renderTable = (table: DocumentTable) => [
  `| ${table.headers.join(' | ')} |`,
  `| ${table.headers.map(() => '---').join(' | ')} |`,
  ...table.rows.map((tableRow) => `| ${tableRow.join(' | ')} |`),
];

export const renderDocumentSectionsMarkdown = (sections: DocumentSection[]) =>
  sections
    .flatMap((section) => [
      `## ${section.title}`,
      ...(section.paragraphs ?? []),
      ...(section.items ?? []).map((item) => `- ${item}`),
      ...(section.table ? renderTable(section.table) : []),
    ])
    .join('\n\n');

export const renderDocumentMarkdown = (document: NonLitigationDocument) =>
  [
    `# ${document.name}`,
    '',
    `适用阶段：${document.phase}`,
    `适用场景：${document.scenario}`,
    '',
    renderDocumentSectionsMarkdown(document.documentSections),
  ].join('\n');

export const renderDocumentTemplateMarkdown = (
  document: NonLitigationDocument,
  template: DocumentTemplateEntry,
) =>
  [
    `# ${template.name}`,
    '',
    `适用阶段：${document.phase}`,
    `适用场景：${template.preview}`,
    '',
    renderDocumentSectionsMarkdown(template.documentSections),
  ].join('\n');
