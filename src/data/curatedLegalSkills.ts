type SkillBlueprint = {
  id: string;
  name: string;
  category: string;
  description: string;
  tags: string[];
  useCases: string[];
  workflow: string[];
  checklist: string[];
  output: string[];
  guardrails: string[];
};

const renderBullets = (items: string[]) => items.map((item) => `- ${item}`).join('\n');

const renderNumbered = (items: string[]) => items.map((item, index) => `${index + 1}. ${item}`).join('\n');

const getFileType = (path: string): SkillFileType => {
  if (path.endsWith('.yaml') || path.endsWith('.yml')) return 'yaml';
  if (path.endsWith('.ts')) return 'typescript';
  if (path.endsWith('.json')) return 'json';
  return 'markdown';
};

const createFile = (skill: SkillBlueprint, path: string, content: string): SkillFile => ({
  id: `${skill.id}-${path.replace(/[^a-z0-9]+/gi, '-').replace(/^-+|-+$/g, '')}`,
  name: path.split('/').pop() ?? path,
  path,
  type: getFileType(path),
  content,
});

